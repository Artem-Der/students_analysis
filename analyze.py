# Крок 3. Зробіть аналіз
# ============================================================
# Потрібно порахувати:
#   - середній бал по класу з кожного предмета (math, python, english);
#   - ім'я студента з найвищим середнім балом (по трьох предметах).

INPUT_FILE = "students.csv"
OUTPUT_FILE = "result.txt"

# TODO 1: відкрийте INPUT_FILE через with open(...) as f:
#   і пропустіть рядок заголовка (next(f))

students_count = 0
total_math = 0
total_python = 0
total_english = 0

student_average = {}

with open(INPUT_FILE, "r", encoding="utf-8") as f:
    next(f)

# TODO 2: пройдіться по рядках файлу (for line in f:), для кожного рядка:
#   - приберіть символ переносу рядка (line.strip())
#   - розбийте рядок по комі (line.split(","))
#   - перетворіть оцінки на числа (int або float)

    for line in f:
        (line.strip())
        (line.split(","))
        name, math_str, python_str, english_str = line.split(",")

        math = float(math_str)
        python = float(python_str)
        english = float(english_str)

        students_count += 1
        total_math += math
        total_python += python
        total_english += english

        student_avg = (math + python + english) / 3
        student_average[name] = student_avg


avg_math = total_math / students_count
avg_python = total_python / students_count
avg_english = total_english / students_count

best_student_name = max(student_average, key=student_average.get)
best_student_score = student_average[best_student_name]

result_text = (
    f"Середній бал по класу:\n"
    f"math: {round(avg_math, 1)}\n"
    f"python: {round(avg_python, 1)}\n"
    f"english: {round(avg_english, 1)}\n\n"
    f"Найкращий студент: {best_student_name} ({round(best_student_score, 1)})"
)

with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
    f.write(result_text)

print(result_text)

